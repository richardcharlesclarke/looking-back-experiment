import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync(new URL('../lib/study-two/results.ts',import.meta.url),'utf8');
const instrument=ts.transpileModule(fs.readFileSync(new URL('../lib/study-two/instrument.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const instrumentUrl='data:text/javascript;base64,'+Buffer.from(instrument).toString('base64');
const {SPEAKER_ITEMS,SPEAKER_VERSION}=await import(instrumentUrl);
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText.replace("'./instrument'",JSON.stringify(instrumentUrl));
const {answerText,beforeStatus,resultGroup,isCurrentBefore,orderedRespondents}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const q={type:'continuous',min:0,max:100,bands:['Strongly disagree','Somewhat disagree','Neither agree nor disagree','Somewhat agree','Strongly agree']};
assert.equal(answerText(q,0),'0 (scale 0–100) — Strongly disagree');
assert.equal(answerText(q,71.23457),'71.23457 (scale 0–100) — Somewhat agree');
assert.equal(answerText(q,100),'100 (scale 0–100) — Strongly agree');
assert.notEqual(answerText(q,undefined),answerText(q,{missing:'skipped'}));
assert.notEqual(answerText(q,{missing:'prefer_not'}),answerText(q,{missing:'cannot_assess'}));
assert.equal(answerText({type:'text'},'First line\n<script>untrusted text</script>'),'First line\n<script>untrusted text</script>');
assert.equal(answerText({type:'rating',min:1,max:7},1),'1 (scale 1–7)');
const current={id:'a',createdAt:'2026-09-15',role:'speaker',isTest:false,consent:{kind:'research'},instrumentVersion:SPEAKER_VERSION,questionnaires:{pre:structuredClone(SPEAKER_ITEMS)},forms:{}};
assert.equal(isCurrentBefore(current),true);
assert.equal(resultGroup({...current,isTest:true}),'test');
assert.equal(resultGroup(current),'research');
assert.equal(resultGroup({...current,consent:undefined}),'other');
assert.equal(resultGroup({...current,instrumentVersion:'old'}),'historical');
assert.equal(resultGroup({...current,questionnaires:{pre:SPEAKER_ITEMS.slice(0,20)}}),'historical');
const altered=structuredClone(current);altered.questionnaires.pre[0].prompt+=' changed';assert.equal(isCurrentBefore(altered),false);
const scale=structuredClone(current);scale.questionnaires.pre[0].max=7;assert.equal(isCurrentBefore(scale),false);
const reordered=structuredClone(current);reordered.questionnaires.pre.reverse();assert.equal(isCurrentBefore(reordered),false);
const later={...current,id:'b',createdAt:'2026-09-16'};
assert.deepEqual(orderedRespondents([later,{...current,forms:{pre:{updatedAt:'2026-09-18'}}}],'research').map(r=>r.id),['a','b']);
assert.deepEqual(orderedRespondents([{...current,isTest:true},altered,later,current],'research').map(r=>r.id),['a','b']);
assert.equal(beforeStatus({forms:{pre:{answers:{q:0}}}}),'Partial');
assert.equal(beforeStatus({forms:{pre:{answers:{},completedAt:'2026-09-17'}}}),'Complete');
assert.equal(beforeStatus({forms:{}}),'No saved answers');
console.log('Results classification, partial/completed states, exact numeric/text values, legacy scales and missing distinctions passed.');
